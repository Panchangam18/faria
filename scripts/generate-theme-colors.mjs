/**
 * One-time script to generate perceptually harmonious theme palettes
 * using pro-color-harmonies (OKLCH color space) and culori.
 *
 * Usage: node scripts/generate-theme-colors.mjs
 */

import { formatHex, parse, converter } from 'culori';
import { generateTintsAndShades } from 'pro-color-harmonies';

const toOklch = converter('oklch');
const toRgb = converter('rgb');

// Our 4 themes with base colors
const THEMES = {
  default: {
    name: 'Chateau',
    background: '#272932',
    text: '#EAE0D5',
    accent: '#C6AC8F',
  },
  comte: {
    name: 'Comte',
    background: '#07020D',
    text: '#FBFFFE',
    accent: '#3C91E6',
  },
  mercedes: {
    name: 'Mercédès',
    background: '#46494C',
    text: '#DCDCDD',
    accent: '#9883E5',
  },
  carnival: {
    name: 'Carnival',
    background: '#001011',
    text: '#6CCFF6',
    accent: '#E94560',
  },
};

function hexToOklch(hex) {
  const color = parse(hex);
  return toOklch(color);
}

function oklchToHex(oklch) {
  const rgb = toRgb(oklch);
  return formatHex(rgb);
}

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return {
    r: parseInt(h.substring(0, 2), 16),
    g: parseInt(h.substring(2, 4), 16),
    b: parseInt(h.substring(4, 6), 16),
  };
}

/**
 * Generate a lighter variant of a background color using OKLCH lightness
 */
function generatePrimaryLight(bgHex) {
  const oklch = hexToOklch(bgHex);
  // Increase lightness by a perceptually even step
  const lighter = { ...oklch, l: Math.min(1, oklch.l + 0.05) };
  return oklchToHex(lighter);
}

/**
 * Generate a darker variant of a background color using OKLCH lightness
 */
function generatePrimaryDark(bgHex) {
  const oklch = hexToOklch(bgHex);
  // Decrease lightness
  const darker = { ...oklch, l: Math.max(0, oklch.l - 0.03) };
  return oklchToHex(darker);
}

/**
 * Generate accent hover/active using pro-color-harmonies tints-and-shades.
 * This gives us perceptually even lightness steps in OKLCH while preserving
 * hue and chroma — much better than simple RGB multiplication.
 */
function generateAccentVariants(accentHex) {
  const oklch = hexToOklch(accentHex);

  // Generate a 6-step tints-and-shades scale (darkest to lightest)
  const palette = generateTintsAndShades({ l: oklch.l, c: oklch.c, h: oklch.h || 0 });

  // Find the entry closest to our accent lightness
  let closestIdx = 0;
  let closestDist = Infinity;
  for (let i = 0; i < palette.length; i++) {
    const dist = Math.abs(palette[i].l - oklch.l);
    if (dist < closestDist) {
      closestDist = dist;
      closestIdx = i;
    }
  }

  // Hover: one step lighter; Active: one step darker
  const hoverIdx = Math.min(palette.length - 1, closestIdx + 1);
  const activeIdx = Math.max(0, closestIdx - 1);

  const hover = oklchToHex({ mode: 'oklch', l: palette[hoverIdx].l, c: palette[hoverIdx].c, h: palette[hoverIdx].h });
  const active = oklchToHex({ mode: 'oklch', l: palette[activeIdx].l, c: palette[activeIdx].c, h: palette[activeIdx].h });

  return { hover, active };
}

/**
 * Generate rgba() string for text opacity variants
 */
function rgbaFromHex(hex, alpha) {
  const { r, g, b } = hexToRgb(hex);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

/**
 * Generate command bar background (semi-transparent primary)
 */
function commandBarBg(hex, alpha) {
  const { r, g, b } = hexToRgb(hex);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

console.log('/* ===== Generated Theme Palettes ===== */');
console.log('/* Generated by scripts/generate-theme-colors.mjs using pro-color-harmonies */');
console.log('/* Do not edit manually — re-run the script to regenerate */\n');

for (const [id, theme] of Object.entries(THEMES)) {
  const primaryLight = generatePrimaryLight(theme.background);
  const primaryDark = generatePrimaryDark(theme.background);
  const accentVariants = generateAccentVariants(theme.accent);

  console.log(`/* ${theme.name} Theme */`);
  console.log(`/* Base: bg=${theme.background}, text=${theme.text}, accent=${theme.accent} */`);
  console.log(`Theme ID: ${id}`);
  console.log(`  --color-primary: ${theme.background};`);
  console.log(`  --color-secondary: ${theme.text};`);
  console.log(`  --color-accent: ${theme.accent};`);
  console.log(`  --color-primary-light: ${primaryLight};`);
  console.log(`  --color-primary-dark: ${primaryDark};`);
  console.log(`  --color-secondary-muted: ${rgbaFromHex(theme.text, 0.7)};`);
  console.log(`  --color-accent-hover: ${accentVariants.hover};`);
  console.log(`  --color-accent-active: ${accentVariants.active};`);
  console.log(`  --color-border: ${rgbaFromHex(theme.text, 0.15)};`);
  console.log(`  --color-hover: ${rgbaFromHex(theme.text, 0.08)};`);
  console.log(`  --color-command-bar-bg: ${commandBarBg(theme.background, 0.7)};`);
  console.log(`  --color-command-bar-menu-bg: ${commandBarBg(theme.background, 0.92)};`);
  console.log('');
}
